import { describe, expect, it } from "vitest";
import { assertSafeKey } from "@/server/storage/types";

describe("assertSafeKey", () => {
  it("rejects absolute and traversal keys", () => {
    expect(() => assertSafeKey("/abs/path")).toThrow();
    expect(() => assertSafeKey("../etc/passwd")).toThrow();
    expect(() => assertSafeKey("evidence/../etc/passwd")).toThrow();
  });

  it("accepts nested keys generated by the app", () => {
    expect(() => assertSafeKey("evidence/2026/10/abc.pdf")).not.toThrow();
    expect(() => assertSafeKey("listings/2026/10/id.thumb.webp")).not.toThrow();
  });
});
